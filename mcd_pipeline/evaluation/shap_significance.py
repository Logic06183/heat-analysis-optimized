"""
SHAP-to-P-Value Bridge — Statistical Significance from SHAP Magnitudes
=======================================================================

Bridges the gap between SHAP-based feature importance (from Stage 1)
and the p-values required by the multiple testing correction framework
(Bonferroni + FDR).

**Approach**: For each biomarker, the mean |SHAP| of temperature lag
features is compared against a null distribution generated by permuting
the temperature columns (breaking the outcome-temperature link while
preserving covariate structure). The p-value is the fraction of null
|SHAP| values >= observed |SHAP|.

This is *not* a standard permutation importance test — it specifically
tests whether temperature contributes SHAP attribution beyond what is
expected by chance, producing a p-value per biomarker per system that
feeds into the Bonferroni/FDR correction.

MCD reference: "Multiple testing: Bonferroni α=0.00625 for 8 biomarker
systems (primary); FDR q=0.10 for individual biomarkers within
significant systems"
"""

